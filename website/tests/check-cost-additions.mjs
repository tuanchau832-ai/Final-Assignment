import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { additionsModel } from '../scripts/cost-additions.mjs';
const prices=JSON.parse(readFileSync(new URL('../content/cost-additions-2026-11-28/price-scope.json',import.meta.url),'utf8'));
const base=JSON.parse(readFileSync(new URL('../content/current-cost-comparison-2026-11-28.json',import.meta.url),'utf8')).selectedCostingBasis;
const m=additionsModel(prices,base);
assert.equal(m.perStationAdditionsVnd,4312000);
assert.equal(m.sharedStarterVnd,1048000);
assert.equal(m.hardwareAndStarterVnd,57466944);
assert.equal(m.priced36MonthScenarioVnd,70398864);
assert.equal(m.completeLifecycleCost,null);
assert.equal(m.sim.cycles,99);
assert.equal(m.hosting.months,36);
assert.equal(m.phSupplySensitivity.totalMlPerBuffer,1980);
assert.equal(m.bufferSensitivity.withFourfoldOverheadBytes,1238630400);
assert.equal(m.powerSensitivity.cases.find(c=>c.loadW===4).nominalAutonomyHours,51);
assert.equal(m.calibrationBenchmark.includedInTotals,false);
assert.throws(()=>additionsModel([...prices,prices[0]],base));
assert.throws(()=>additionsModel([{...prices[0],unitVnd:0}],base));
console.log('Reference additions: package scope, shared starters once, billing units, sensitivity and unknown lifecycle total pass.');
